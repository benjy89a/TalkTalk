-- 문제
--   * DM 은 "이미 있는지 화면에서 찾아보고, 없으면 만든다" 방식(components/channel/dm.ts)
--   * 두 사람이 거의 동시에 서로에게 "새 DM" 을 누르면 둘 다 "없음" 으로 보고 DM 을 2개 만든다
--     → DM 목록에 같은 이름이 두 번, 대화가 두 방으로 나뉨
--   * 001 의 channels_name_unique 는 DM 을 일부러 빼 두어서(where type <> 'dm') DB 가 막지 못했다
--
-- 해결
--   * DM 이름은 두 사람 id 를 정렬해 붙인 값(dm:{작은id}:{큰id})이라 같은 두 사람이면 항상 같다
--     → DM 끼리만 이름이 겹치지 못하게 유니크 인덱스를 추가
--   * 동시에 눌러 늦게 만든 쪽은 23505 에러("같은 이름의 채널이 이미 있어요")를 한 번 보고,
--     다시 누르면 이미 만들어진 DM 이 열린다. (C 의 dm.ts 에서 23505 를 받으면 기존 DM 을
--     바로 열도록 고치면 더 매끄럽다 — 선택 사항)
--   * DM 에는 "나가기" 버튼이 없으므로 "나간 사람이 다시 DM 을 못 만드는" 문제는 생기지 않는다
-- =====================================================================


